import { parseExtrusionRoleComment } from '../gcode-extrusion-roles'
import { ExtrusionRole } from '@/store/gcodePreview/types'

describe('parseExtrusionRoleComment', () => {
  it.each([
    ['TYPE:Perimeter', ExtrusionRole.Perimeter],
    ['TYPE:External perimeter', ExtrusionRole.ExternalPerimeter],
    ['TYPE:Skirt', ExtrusionRole.Skirt],
    ['TYPE:Skirt/Brim', ExtrusionRole.Skirt],
    ['TYPE:Wipe tower', ExtrusionRole.WipeTower],
    ['TYPE:Outer wall', ExtrusionRole.ExternalPerimeter],
    ['FEATURE: Sparse infill', ExtrusionRole.InternalInfill],
    ['FEATURE: Brim', ExtrusionRole.Skirt],
    ['FEATURE: Bottom surface', ExtrusionRole.SolidInfill],
    ['TYPE:Internal bridge', ExtrusionRole.BridgeInfill],
    ['TYPE:Internal Bridge', ExtrusionRole.BridgeInfill],
    ['FEATURE: Support transition', ExtrusionRole.None],
    ['TYPE:FILL', ExtrusionRole.InternalInfill],
    ['TYPE:SKIN', ExtrusionRole.SolidInfill],
    ['TYPE:WALL-OUTER', ExtrusionRole.ExternalPerimeter],
    ['TYPE:BOTTOM-SURFACE', ExtrusionRole.None],
    ['feature outer perimeter', ExtrusionRole.ExternalPerimeter],
    ['feature dense support', ExtrusionRole.SupportMaterialInterface],
    ['\'Perimeter Path\'', ExtrusionRole.ExternalPerimeter],
    ['\'Support (may Stack) Path\', 0.4 [feed mm/s]', ExtrusionRole.SupportMaterial],
    ['\'Crown Path\'', ExtrusionRole.None],
    ['@AreaBegin "Support"', ExtrusionRole.SupportMaterial],
    ['@AreaBegin "SupportInterface"', ExtrusionRole.SupportMaterialInterface],
    ['@AreaBegin "Shell"', ExtrusionRole.None]
  ])('maps %s', (comment, role) => {
    expect(parseExtrusionRoleComment(comment)).toBe(role)
  })

  it.each([
    'LAYER_CHANGE',
    'WIDTH:0.45',
    'generated by PrusaSlicer 2.8.0',
    'type:Perimeter',
    '\'quoted text\''
  ])('ignores %s', (comment) => {
    expect(parseExtrusionRoleComment(comment)).toBeUndefined()
  })
})
